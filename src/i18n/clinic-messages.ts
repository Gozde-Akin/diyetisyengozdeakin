function deepMerge(base: Messages, override: Messages): Messages {
  const result: Messages = { ...base };

  for (const [key, value] of Object.entries(override)) {
    const current = result[key];
    if (
      value &&
      typeof value === "object" &&
      !Array.isArray(value) &&
      current &&
      typeof current === "object" &&
      !Array.isArray(current)
    ) {
      result[key] = deepMerge(current as Messages, value as Messages);
    } else {
      result[key] = value;
    }
  }

  return result;
}

export function applyClinicMessageOverrides(locale: string, messages: Messages): Messages {
  return deepMerge(messages, clinicOverrides[locale] ?? clinicOverrides.tr);
}
